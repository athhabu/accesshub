function initDB() {
  const dir = path.dirname(DB_PATH);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  if (!fs.existsSync(DB_PATH)) {
    fs.writeFileSync(DB_PATH, JSON.stringify(INITIAL_DATA, null, 2), 'utf-8');
  }
}

function readDB() {
  initDB();
  try {
    const data = fs.readFileSync(DB_PATH, 'utf-8');
    const db = JSON.parse(data);
    if (!db.expenses || !Array.isArray(db.expenses)) {
      db.expenses = INITIAL_DATA.expenses;
      writeDB(db);
    }
    if (!db.events || !Array.isArray(db.events)) {
      db.events = INITIAL_DATA.events;
      writeDB(db);
    }
    // Initialize securityAssessment if missing (upgrade migration)
    if (!db.securityAssessment || !db.securityAssessment.checks) {
      const checks = {};
      for (let i = 1; i <= 20; i++) {
        checks[i] = { status: 'pending', verifiedAt: null };
      }
      db.securityAssessment = { checks };
      writeDB(db);
    }
    return db;
  } catch (err) {
    console.error('Error reading database:', err);
    return INITIAL_DATA;
  }
}

function writeDB(data) {
  initDB();
  fs.writeFileSync(DB_PATH, JSON.stringify(data, null, 2), 'utf-8');
}

module.exports = {
  readDB,
  writeDB,
  initDB
};
